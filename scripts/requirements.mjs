import fs from "node:fs";
import assert from "node:assert/strict";
const { requirements: r } = JSON.parse(
  fs.readFileSync("docs/requirements.json", "utf8"),
);
const expected = Object.entries({
  "FE-FR": 34,
  "BE-FR": 37,
  "FE-NFR": 18,
  "BE-NFR": 28,
  GAP: 10,
  WEB: 19,
}).flatMap(([p, n]) =>
  Array.from({ length: n }, (_, i) => `${p}-${String(i + 1).padStart(2, "0")}`),
);
assert.equal(r.length, 146);
assert.equal(new Set(r.map((x) => x.id)).size, 146);
assert.deepEqual(r.map((x) => x.id).sort(), expected.sort());
const statuses = [
  "Not started",
  "In progress",
  "Implemented but unverified",
  "Verified",
  "Blocked",
  "Optional/deferred",
];
for (const x of r) {
  assert(statuses.includes(x.status));
  for (const k of [
    "description",
    "classification",
    "owner",
    "phase",
    "frontend_workflow",
    "dependencies",
    "tests",
    "evidence",
    "blockers",
  ])
    assert(x[k] !== undefined, `${x.id} ${k}`);
  assert(x.acceptance_criteria.length);
  if (x.status === "Verified")
    assert(x.evidence.length, `${x.id} lacks evidence`);
  if (x.classification === "Required") assert(x.status !== "Optional/deferred");
}
fs.writeFileSync(
  "docs/TRACEABILITY.md",
  "# Requirement traceability\n\nGenerated by `node scripts/requirements.mjs`. All 146 primary entries are retained. Full criteria/dependencies in [register](requirements.json). Status applies to the entire requirement.\n\n| ID | Acceptance scope | Owner / phase | Status | Evidence / blockers |\n|---|---|---|---|---|\n" +
    r
      .map(
        (x) =>
          `| ${x.id} | ${x.description.replaceAll("|", "/")} | ${x.owner} / ${x.phase} | ${x.status} | ${[...x.evidence, ...x.blockers].join("; ") || "—"} |`,
      )
      .join("\n") +
    "\n",
);
console.log(
  `Validated ${r.length} unique baseline requirements.`,
  r.reduce((a, x) => ((a[x.status] = (a[x.status] || 0) + 1), a), {}),
);
